package com.recruiting.platform.accounts.file.app;

import com.recruiting.platform.accounts.domain.CvIntakeItem;
import com.recruiting.platform.accounts.domain.CvIntakeItemRepository;
import com.recruiting.platform.accounts.domain.PersonFile;
import com.recruiting.platform.accounts.domain.PersonFileRepository;
import com.recruiting.platform.contracts.CvIntakeStatus;
import com.recruiting.platform.contracts.FileStore;
import com.recruiting.platform.contracts.TextExtractionStatus;
import java.io.InputStream;
import java.time.Instant;
import java.util.List;
import java.util.UUID;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionTemplate;

/**
 * Async worker (no AI, no OCR): Apache Tika fills {@code person_file.extracted_text} (the tsvector is generated by the
 * database) and, for CV intake items, the detected e-mails, phones and LinkedIn URLs. Picks up PENDING rows.
 */
@Component
public class TextExtractionWorker {

    private static final Logger LOG = LoggerFactory.getLogger(TextExtractionWorker.class);

    private final PersonFileRepository files;
    private final CvIntakeItemRepository items;
    private final FileStore store;
    private final TextExtractor extractor;
    private final TransactionTemplate tx;

    public TextExtractionWorker(PersonFileRepository files, CvIntakeItemRepository items, FileStore store,
            TextExtractor extractor, TransactionTemplate tx) {
        this.files = files;
        this.items = items;
        this.store = store;
        this.extractor = extractor;
        this.tx = tx;
    }

    @Scheduled(fixedDelayString = "${app.files.extraction-delay-ms:3000}")
    public void run() {
        try {
            runOnce();
        } catch (RuntimeException e) {
            LOG.warn("Text extraction run failed: {}", e.toString());
        }
    }

    /** Processes up to 10 pending files and 10 pending intake items; returns how many were handled. */
    public int runOnce() {
        int n = 0;
        List<UUID> fileIds = tx.execute(s -> files.findPendingText(10).stream().map(PersonFile::getId).toList());
        for (UUID id : fileIds) {
            n += handle(() -> tx.executeWithoutResult(s -> files.findById(id).ifPresent(this::extract)));
        }
        List<UUID> itemIds = tx.execute(s -> items
                .findTop10ByStatusAndTextStatusOrderByUploadedAt(CvIntakeStatus.PENDING, TextExtractionStatus.PENDING)
                .stream().map(CvIntakeItem::getId).toList());
        for (UUID id : itemIds) {
            n += handle(() -> tx.executeWithoutResult(s -> items.findById(id).ifPresent(this::extract)));
        }
        return n;
    }

    private int handle(Runnable r) {
        try {
            r.run();
            return 1;
        } catch (RuntimeException e) {
            // another worker or an upload in the same moment; the next run retries
            LOG.debug("Extraction skipped: {}", e.toString());
            return 0;
        }
    }

    private void extract(PersonFile f) {
        if (f.getTextStatus() != TextExtractionStatus.PENDING) {
            return;
        }
        String[] result = parse(f.getStorageKey());
        f.setTextStatus(TextExtractionStatus.valueOf(result[0]));
        f.setExtractedText(result[1]);
        f.setExtractedAt(Instant.now());
        files.saveAndFlush(f);
    }

    private void extract(CvIntakeItem item) {
        if (item.getStatus() != CvIntakeStatus.PENDING || item.getTextStatus() != TextExtractionStatus.PENDING
                || item.getStorageKey() == null) {
            return;
        }
        String[] result = parse(item.getStorageKey());
        item.setTextStatus(TextExtractionStatus.valueOf(result[0]));
        item.setExtractedText(result[1]);
        item.setDetected(result[1] == null ? null : ContactDetector.detect(result[1]));
        items.saveAndFlush(item);
    }

    /** [status, text]: DONE with text, NO_TEXT when empty, FAILED when the file cannot be read or parsed. */
    private String[] parse(String key) {
        try {
            byte[] bytes;
            InputStream in = store.get(key).orElse(null);
            if (in == null) {
                return new String[] {TextExtractionStatus.FAILED.name(), null};
            }
            try (in) {
                bytes = in.readAllBytes();
            }
            String text = extractor.extract(bytes);
            if (text.isBlank()) {
                return new String[] {TextExtractionStatus.NO_TEXT.name(), null};
            }
            return new String[] {TextExtractionStatus.DONE.name(), text};
        } catch (Exception e) {
            LOG.debug("Tika could not parse {}: {}", key, e.toString());
            return new String[] {TextExtractionStatus.FAILED.name(), null};
        }
    }
}
